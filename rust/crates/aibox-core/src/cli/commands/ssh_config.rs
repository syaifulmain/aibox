use crate::cli::commands::require_environment;
use crate::cli::{CliIo, ExitCode, ParsedArgs};
use crate::engine::Engine;
use crate::process::CommandRunner;
use crate::util::shell::shell_quote;

/// Renders a single SSH client config stanza (`Host aibox-<env>`) using `incus exec`.
pub fn render_ssh_config_entry(env_name: &str) -> String {
    let q_name = shell_quote(env_name);
    format!(
        "Host aibox-{env_name}\n\
         \x20   User root\n\
         \x20   StrictHostKeyChecking no\n\
         \x20   UserKnownHostsFile /dev/null\n\
         \x20   ProxyCommand incus exec {q_name} -- sh -c 'if [ -x /usr/sbin/sshd ]; then exec /usr/sbin/sshd -i; elif [ -x /usr/bin/sshd ]; then exec /usr/bin/sshd -i; else exec nc 127.0.0.1 22; fi'\n"
    )
}

/// Renders an SSH config snippet for the given environment names.
pub fn render_ssh_config(env_names: &[String]) -> String {
    if env_names.is_empty() {
        return "# Generated by aibox ssh-config\n# No environments found.\n".to_string();
    }
    let mut out = String::from("# Generated by aibox ssh-config\n\n");
    for (idx, name) in env_names.iter().enumerate() {
        if idx > 0 {
            out.push('\n');
        }
        out.push_str(&render_ssh_config_entry(name));
    }
    out
}

pub fn run_ssh_config(
    engine: &mut Engine,
    parsed: &ParsedArgs,
    io: &mut dyn CliIo,
    runner: &dyn CommandRunner,
) -> i32 {
    if !parsed.env_name.is_empty() {
        let env = match require_environment(engine, io, runner, &parsed.env_name, true) {
            Ok(e) => e,
            Err(rc) => return rc,
        };
        let text = render_ssh_config(&[env.name]);
        io.write_stdout(text.as_bytes());
        return ExitCode::Ok.as_i32();
    }

    if let Err(err) = engine.refresh_sync(runner) {
        io.write_stderr(format!("Error: {err}\n").as_bytes());
        return ExitCode::Failed.as_i32();
    }

    let mut names: Vec<String> = engine
        .environments
        .iter()
        .filter(|e| !e.is_template)
        .map(|e| e.name.clone())
        .collect();
    names.sort();

    let text = render_ssh_config(&names);
    io.write_stdout(text.as_bytes());
    ExitCode::Ok.as_i32()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cli::parse_args;
    use crate::process::CommandOutput;

    struct DummyIo {
        stdout: Vec<u8>,
        stderr: Vec<u8>,
    }

    impl DummyIo {
        fn new() -> Self {
            Self {
                stdout: Vec::new(),
                stderr: Vec::new(),
            }
        }
    }

    impl CliIo for DummyIo {
        fn write_stdout(&mut self, data: &[u8]) {
            self.stdout.extend_from_slice(data);
        }

        fn write_stderr(&mut self, data: &[u8]) {
            self.stderr.extend_from_slice(data);
        }

        fn read_line(&mut self) -> Option<String> {
            None
        }

        fn run_forwarded(&mut self, _program: &str, _args: &[String]) -> i32 {
            0
        }

        fn exec_replace(&mut self, _program: &str, _args: &[String]) -> i32 {
            0
        }
    }

    struct ListRunner(String);

    impl CommandRunner for ListRunner {
        fn run(&self, program: &str, args: &[&str]) -> CommandOutput {
            if program == "incus" && args.first() == Some(&"list") {
                return CommandOutput {
                    exit_code: 0,
                    std_out: self.0.clone(),
                    std_err: String::new(),
                };
            }
            CommandOutput {
                exit_code: 0,
                std_out: String::new(),
                std_err: String::new(),
            }
        }

        fn socket_writable(&self, _path: &str) -> bool {
            true
        }
    }

    #[test]
    fn renders_single_and_multiple_ssh_config_entries() {
        let one = render_ssh_config(&["dev-box".to_string()]);
        assert!(one.contains("Host aibox-dev-box"));
        assert!(one.contains("ProxyCommand incus exec 'dev-box'"));

        let empty = render_ssh_config(&[]);
        assert!(empty.contains("No environments found."));
    }

    #[test]
    fn run_ssh_config_handles_all_single_template_and_missing() {
        let dir = std::env::temp_dir().join("aibox_ssh_cfg_test");
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("mkdir");
        let mut engine = Engine::new(Some(&dir.to_string_lossy()), true, "/tmp");
        let runner = ListRunner(
            r#"[
                {"name":"zeta","type":"container","status":"Running","config":{}},
                {"name":"alpha","type":"container","status":"Stopped","config":{}},
                {"name":"tpl","type":"container","status":"Stopped","config":{"user.aibox.template":"true"}}
            ]"#
            .to_string(),
        );

        let mut io_all = DummyIo::new();
        let rc_all = run_ssh_config(
            &mut engine,
            &parse_args(&["ssh-config".to_string()]),
            &mut io_all,
            &runner,
        );
        assert_eq!(rc_all, 0);
        let out_all = String::from_utf8_lossy(&io_all.stdout);
        let alpha_pos = out_all.find("Host aibox-alpha").expect("alpha");
        let zeta_pos = out_all.find("Host aibox-zeta").expect("zeta");
        assert!(alpha_pos < zeta_pos);
        assert!(!out_all.contains("Host aibox-tpl"));

        let mut io_one = DummyIo::new();
        let rc_one = run_ssh_config(
            &mut engine,
            &parse_args(&["ssh-config".to_string(), "alpha".to_string()]),
            &mut io_one,
            &runner,
        );
        assert_eq!(rc_one, 0);
        let out_one = String::from_utf8_lossy(&io_one.stdout);
        assert!(out_one.contains("Host aibox-alpha"));
        assert!(!out_one.contains("Host aibox-zeta"));

        let mut io_tpl = DummyIo::new();
        assert_eq!(
            run_ssh_config(
                &mut engine,
                &parse_args(&["ssh-config".to_string(), "tpl".to_string()]),
                &mut io_tpl,
                &runner,
            ),
            ExitCode::NotFound.as_i32()
        );

        let mut io_missing = DummyIo::new();
        assert_eq!(
            run_ssh_config(
                &mut engine,
                &parse_args(&["ssh-config".to_string(), "nope".to_string()]),
                &mut io_missing,
                &runner,
            ),
            ExitCode::NotFound.as_i32()
        );

        let _ = std::fs::remove_dir_all(&dir);
    }
}
