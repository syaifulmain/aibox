//! Task runtime state files and lock/metadata helpers.
//!
//! All task state lives under `<state_dir>` (e.g. `~/.local/share/aibox/.state`
//! or `<project>/.aibox/state`).
//!
//! ## On-disk formats (must remain byte-compatible with pre-migration C++):
//!
//! - `task.pid`: ASCII decimal PID followed by a newline (`"<pid>\n"`). Read
//!   with ASCII whitespace trimmed and parsed as `i64` (returns `0` when
//!   missing, unreadable, or invalid).
//! - `task.meta`: Compact JSON object (`{...}`) with keys:
//!   - `description` (string): human-readable task description.
//!   - `envName` (string): created or primary environment name (may be empty).
//!   - `targetEnvName` (string): target environment for history attribution.
//!   - `downloadingOsId` (string, optional): OS image id if downloading an OS.
//!   - `startedAt` (string): local ISO-8601 timestamp (`YYYY-MM-DDTHH:MM:SS`).
//!   - `reason` (string, optional): operation reason tag (e.g. `"auto"`).
//! - `task.log`: Raw PTY/stdout+stderr byte stream from the running `task.sh`
//!   process. May contain ANSI escape sequences, `\r` progress overwrites,
//!   `@@STAGE:<pct>:<label>` markers, and `@@EXIT:<code>` marker. Redacted in
//!   place for secret values upon completion/cancellation.
//! - `task.sh`: Executable (`0700`) bash wrapper generated by `run_shell_task`,
//!   running the inner script in a subshell, echoing `@@EXIT:$CODE`, sending
//!   `notify-send` if available, and exiting with `$CODE`.

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

use regex::Regex;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TaskMeta {
    #[serde(default)]
    pub description: String,
    #[serde(default)]
    pub env_name: String,
    #[serde(default)]
    pub target_env_name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub downloading_os_id: Option<String>,
    #[serde(default)]
    pub started_at: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

pub fn task_pid_path(state_dir: &Path) -> PathBuf {
    state_dir.join("task.pid")
}

pub fn task_meta_path(state_dir: &Path) -> PathBuf {
    state_dir.join("task.meta")
}

pub fn task_log_path(state_dir: &Path) -> PathBuf {
    state_dir.join("task.log")
}

pub fn task_script_path(state_dir: &Path) -> PathBuf {
    state_dir.join("task.sh")
}

pub fn read_task_pid(state_dir: &Path) -> i64 {
    let Ok(raw) = fs::read_to_string(task_pid_path(state_dir)) else {
        return 0;
    };
    raw.trim().parse::<i64>().unwrap_or(0)
}

pub fn write_task_pid(state_dir: &Path, pid: i64) -> Result<(), String> {
    fs::create_dir_all(state_dir).map_err(|e| format!("Failed to create state dir: {e}"))?;
    fs::write(task_pid_path(state_dir), format!("{pid}\n"))
        .map_err(|e| format!("Failed to write task.pid: {e}"))
}

pub fn read_task_meta(state_dir: &Path) -> Option<TaskMeta> {
    let bytes = fs::read(task_meta_path(state_dir)).ok()?;
    serde_json::from_slice::<TaskMeta>(&bytes).ok()
}

pub fn write_task_meta(state_dir: &Path, meta: &TaskMeta) -> Result<(), String> {
    fs::create_dir_all(state_dir).map_err(|e| format!("Failed to create state dir: {e}"))?;
    let json =
        serde_json::to_string(meta).map_err(|e| format!("Failed to serialize task.meta: {e}"))?;
    fs::write(task_meta_path(state_dir), json)
        .map_err(|e| format!("Failed to write task.meta: {e}"))
}

/// Removes `task.pid`, `task.meta`, and `task.sh`. Leaves `task.log` intact.
pub fn clear_task_files(state_dir: &Path) {
    let _ = fs::remove_file(task_pid_path(state_dir));
    let _ = fs::remove_file(task_meta_path(state_dir));
    let _ = fs::remove_file(task_script_path(state_dir));
}

/// Extracts an admin fix command from an error/status message.
///
/// Checks each line for `Fix (admin): <cmd>` (case-insensitive) first, then
/// `\brun:\s*(sudo\s+.+)$` (case-insensitive). Returns empty string if none.
pub fn admin_fix_command(message: &str) -> String {
    static FIX_RE: OnceLock<Regex> = OnceLock::new();
    static RUN_RE: OnceLock<Regex> = OnceLock::new();

    let fix_re =
        FIX_RE.get_or_init(|| Regex::new(r"(?i)Fix \(admin\):\s*(.+)$").expect("valid fix regex"));
    let run_re =
        RUN_RE.get_or_init(|| Regex::new(r"(?i)\brun:\s*(sudo\s+.+)$").expect("valid run regex"));

    for line in message.split('\n') {
        if let Some(caps) = fix_re.captures(line) {
            if let Some(m) = caps.get(1) {
                return m.as_str().trim().to_string();
            }
        }
        if let Some(caps) = run_re.captures(line) {
            if let Some(m) = caps.get(1) {
                return m.as_str().trim().to_string();
            }
        }
    }
    String::new()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temp_dir(name: &str) -> PathBuf {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("time")
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("aibox_task_files_{name}_{nanos}"));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("mkdir");
        dir
    }

    #[test]
    fn pid_and_meta_round_trip_and_clear() {
        let dir = temp_dir("roundtrip");
        assert_eq!(read_task_pid(&dir), 0);
        assert!(read_task_meta(&dir).is_none());

        write_task_pid(&dir, 4242).expect("write pid");
        assert_eq!(read_task_pid(&dir), 4242);

        let meta = TaskMeta {
            description: "Starting 'dev'".to_string(),
            env_name: "dev".to_string(),
            target_env_name: "dev".to_string(),
            downloading_os_id: None,
            started_at: "2026-11-17T10:00:00".to_string(),
            reason: None,
        };
        write_task_meta(&dir, &meta).expect("write meta");
        assert_eq!(read_task_meta(&dir), Some(meta));

        fs::write(task_log_path(&dir), "log").expect("write log");
        fs::write(task_script_path(&dir), "#!/bin/sh\n").expect("write sh");

        clear_task_files(&dir);
        assert!(!task_pid_path(&dir).exists());
        assert!(!task_meta_path(&dir).exists());
        assert!(!task_script_path(&dir).exists());
        assert!(task_log_path(&dir).exists());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn admin_fix_command_extracts_expected_lines() {
        assert_eq!(
            admin_fix_command("Fix (admin): sudo sysctl -w net.ipv4.ip_forward=1"),
            "sudo sysctl -w net.ipv4.ip_forward=1"
        );
        assert_eq!(
            admin_fix_command("Please run: sudo usermod -aG incus-admin alice"),
            "sudo usermod -aG incus-admin alice"
        );
        assert_eq!(admin_fix_command("run: echo not-sudo"), "");
    }
}
